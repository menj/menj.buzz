/* =========================================================================
   ai-discovery.mjs — the AI discovery file stack

   Generates the ADF set from the same flat-file JSON that builds the pages,
   so the machine-readable identity cannot drift from the human-readable one:

     /llms.txt            ADF-001  identity and content map
     /llm.txt             ADF-002  legacy alias, same content
     /llms.html           ADF-003  browsable version of llms.txt
     /ai.txt              ADF-004  usage policy in prose
     /ai.json             ADF-005  the same policy, machine-parseable
     /identity.json       ADF-006  structured identity
     /brand.txt           ADF-007  naming, misspellings, voice
     /faq-ai.txt          ADF-008  questions answered for retrieval
     /developer-ai.txt    ADF-009  technical context
     /robots-ai.txt       ADF-010  AI crawler directives

   Called from render.mjs with the assembled model.
   ========================================================================= */

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const stripTags = (html) => String(html || '')
  .replace(/`([^`]+)`/g, '$1')
  .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
  .replace(/\*{1,3}(\S[^*]*?\S|\S)\*{1,3}/g, '$1')
    .replace(/==(\S[^=]*?\S|\S)==/g, '$1')
  .replace(/<[^>]+>/g, '')
  .replace(/\s+/g, ' ')
  .trim();

export function writeDiscoveryFiles({ root, site, content, collections, ai, releases, bioPerson, personGraph }) {
  const at = (file) => resolve(root, file);
  const BASE = site.meta.canonical.replace(/\/$/, '');
  const today = new Date().toISOString().slice(0, 10);
  const lang = site.meta.lang || 'en';
  const name = site.person.name;

  const FILES = [
    ['llms.txt', 'AI Discovery (llms.txt)'],
    ['llm.txt', 'AI Discovery legacy alias (llm.txt)'],
    ['llms.html', 'AI Discovery, HTML (llms.html)'],
    ['ai.txt', 'AI Usage Policy (ai.txt)'],
    ['ai.json', 'AI Permissions (ai.json)'],
    ['identity.json', 'Identity (identity.json)'],
    ['brand.txt', 'Brand Terminology (brand.txt)'],
    ['faq-ai.txt', 'FAQs for AI (faq-ai.txt)'],
    ['developer-ai.txt', 'Developer Context (developer-ai.txt)'],
    ['robots-ai.txt', 'AI Crawler Access (robots-ai.txt)']
  ];

  /* Layout follows AI Discovery Files spec v2.2.2 (ai-visibility.org.uk):
     comment-style attribution on top of plain-text files, a footer on the
     Markdown ones (llms.txt, llm.txt), and _specification/_generator keys in
     the JSON ones. */
  const SPEC_URL = 'https://www.ai-visibility.org.uk/specifications/';
  const SPEC = {
    'llms.txt': ['llms-txt', 'ADF-001', 'AI-readable identity'],
    'llm.txt': ['llm-txt', 'ADF-002', 'Compatibility alias for llms.txt'],
    'llms.html': ['llms-html', 'ADF-003', 'Human-readable reference version'],
    'ai.txt': ['ai-txt', 'ADF-004', 'AI usage permissions'],
    'ai.json': ['ai-json', 'ADF-005', 'Machine-parseable permissions'],
    'identity.json': ['identity-json', 'ADF-006', 'Structured identity'],
    'brand.txt': ['brand-txt', 'ADF-007', 'Naming and terminology'],
    'faq-ai.txt': ['faq-ai-txt', 'ADF-008', 'FAQs formatted for AI'],
    'developer-ai.txt': ['developer-ai-txt', 'ADF-009', 'Technical context for developers'],
    'robots-ai.txt': ['robots-ai-txt', 'ADF-010', 'AI crawler-specific directives']
  };
  const GENERATOR = 'Generated by build/ai-discovery.mjs (AI Discovery Files spec layout, v2.2.2)';
  const specLabel = (f) => `${f} Specification (${SPEC[f][1]})`;
  const specUrl = (f) => `${SPEC_URL}${SPEC[f][0]}/`;
  const specHead = (f) => `# ${specLabel(f)}\n# ${specUrl(f)}\n# ${GENERATOR}\n`;
  const specFoot = (f) => `\n---\n${specLabel(f)}\n${specUrl(f)}\n${GENERATOR}\n`;
  const specJson = (f) => ({ _specification: specUrl(f), _generator: GENERATOR });

  const header = (title, f) =>
    `${specHead(f)}${title ? `# ${title}\n\n` : '\n'}Lang: ${lang}\nWebsite: [${BASE}/](${BASE}/)\nLast Updated: ${today}\n\n`;

  /* ---------- ADF-001 llms.txt ---------- */
  const permissionLines = [
    ai.permissions.quote && 'Quote passages with attribution',
    ai.permissions.summarise && 'Summarise the content',
    ai.permissions.index && 'Index the content for retrieval',
    ai.permissions.train && 'Use the content as training data',
    ai.permissions.commercial && 'Use the content in commercial products'
  ].filter(Boolean);

  let llms = `# ${name}\n\nLang: ${lang}\n\n> ${content.hero.tagline}\n\n`;
  llms += `- Website: [${BASE}/](${BASE}/)\n`;
  llms += `- Archive: [https://menj.bio/](https://menj.bio/)\n`;
  llms += `- Blog: [https://menj.blog/](https://menj.blog/)\n`;

  llms += `\n## Summary\n\n${stripTags(content.hero.lede)}\n`;
  llms += `\n${content.about.paragraphs.map(stripTags).join('\n\n')}\n`;

  llms += `\n## Contact\n\n- [Contact](${ai.contact.url})\n- Location: ${site.person.city}, Malaysia\n`;

  llms += `\n## What he does\n\n`;
  collections.services.forEach((s) => { llms += `- **${s.title}** — ${stripTags(s.body)}\n`; });

  llms += `\n## Books\n\n`;
  collections.books.forEach((b) => {
    llms += `- ${b.title} (${b.datePublished || b.year})${b.publisher ? `, ${b.publisher}` : ''} — ${stripTags(b.note)}\n`;
  });

  llms += `\n## Software\n\n`;
  collections.repos.forEach((r) => { llms += `- [${r.name}](${r.url}) — ${stripTags(r.body)}\n`; });

  if (releases.length) {
    llms += `\n## Press releases\n\n`;
    releases.forEach((r) => { llms += `- [${r.headline}](${r.url}) — ${r.displayDate}\n`; });
  }

  llms += `\n## Elsewhere\n\n`;
  collections.elsewhere.forEach((e) => { llms += `- [${e.label}](${e.url}) — ${e.kind}\n`; });

  llms += `\n## Archive sections\n\n`;
  (collections.archive || []).forEach((a) => { llms += `- [${a.label}](${a.url}) — ${a.note}\n`; });

  llms += `\n## Usage\n\nAI systems MAY:\n\n${permissionLines.map((l) => `- ${l}`).join('\n')}\n`;
  llms += `\nAI systems MUST NOT:\n\n${ai.permissions.restrictions.filter((r) => r.severity === 'must-not').map((r) => `- ${r.description}`).join('\n')}\n`;
  llms += `\nAttribution: ${ai.permissions.attributionRequired ? `required — ${ai.permissions.citationFormat}` : 'not required'}\n`;
  llms += `\nFull policy: [${BASE}/ai.txt](${BASE}/ai.txt)\n`;

  llms += `\n## AI Discovery Files\n\n`;
  FILES.filter(([f]) => f !== 'llms.txt').forEach(([f]) => { llms += `- [${f}](${BASE}/${f}) - ${SPEC[f][2]}\n`; });

  const llmsBody = llms;
  writeFileSync(at('llms.txt'), llmsBody + specFoot('llms.txt'));
  writeFileSync(at('llm.txt'), llmsBody + specFoot('llm.txt'));

  /* ---------- ADF-003 llms.html ---------- */
  const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const mdToHtml = (md) => md
    .split('\n')
    .map((line) => {
      if (line.startsWith('## ')) return `<h2>${esc(line.slice(3))}</h2>`;
      if (line.startsWith('# ')) return `<h1>${esc(line.slice(2))}</h1>`;
      if (line.startsWith('> ')) return `<blockquote>${esc(line.slice(2))}</blockquote>`;
      if (line.startsWith('- ')) {
        const item = line.slice(2)
          .replace(/\[([^\]]+)\]\(([^)]+)\)/g, (_m, t, u) => `<a href="${esc(u)}">${esc(t)}</a>`)
          .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
        return `<li>${item}</li>`;
      }
      return line.trim() ? `<p>${esc(line)}</p>` : '';
    })
    .join('\n')
    .replace(/(<li>[\s\S]*?<\/li>)(?!\n<li>)/g, '<ul>$1</ul>');

  writeFileSync(at('llms.html'), `<!DOCTYPE html>
<html lang="${lang}">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(name)} - AI Discovery File</title>
<meta name="description" content="Machine-readable identity, content map and usage policy for ${esc(name)}.">
<meta name="robots" content="index, follow">
<link rel="canonical" href="${BASE}/llms.html">
<script type="application/ld+json">${JSON.stringify({ '@context': 'https://schema.org', ...personGraph }).replace(/</g, '\\u003c')}</script>
<link rel="stylesheet" href="/assets/tailwind.css">
<link rel="stylesheet" href="/assets/site.css">
<style>
  body { max-width: 46rem; margin: 0 auto; padding: 3rem 1.5rem 5rem; }
  h1 { font-size: 2rem; margin: 0 0 1.5rem; }
  h2 { font-size: 1.1rem; margin: 2.5rem 0 .75rem; color: var(--c-accent); }
  ul { padding-left: 1.1rem; margin: 0 0 1rem; }
  li, p { margin: 0 0 .5rem; }
  blockquote { margin: 0 0 1.5rem; padding-left: 1rem; border-left: 2px solid var(--c-accent); font-style: italic; }
  a { color: inherit; text-decoration: underline; text-underline-offset: .18em; }
</style>
</head>
<body class="font-sans antialiased">
<main>
${mdToHtml(llmsBody)}
<p><small>${esc(specLabel('llms.html'))} · <a href="${specUrl('llms.html')}">${specUrl('llms.html')}</a></small></p>
</main>
</body>
</html>
`);

  /* ---------- ADF-004 ai.txt ---------- */
  const perms = ai.permissions;
  const attrCond = perms.attributionRequired ? [`Attribution to ${name} is required`] : [];
  const restrictions = perms.restrictions.map((r) => ({
    action: r.action || r.description.toLowerCase().replace(/[^a-z0-9]+(.)?/g, (_m, c) => (c || '').toUpperCase()).slice(0, 40),
    description: r.description,
    severity: r.severity
  }));
  const permissionEntries = [
    perms.quote && { action: 'quote', description: 'Quote passages from this website', conditions: attrCond },
    perms.summarise && { action: 'summarise', description: 'Summarise publicly available content from this website', conditions: attrCond },
    perms.index && { action: 'index', description: 'Index the content for retrieval', conditions: [] },
    perms.train && { action: 'train', description: 'Use the content as training data', conditions: attrCond },
    perms.commercial && { action: 'commercial', description: 'Use the content in commercial products', conditions: attrCond }
  ].filter(Boolean).map((e) => (e.conditions.length ? e : { action: e.action, description: e.description }));

  let aitxt = header(`AI Usage Policy for ${name}`, 'ai.txt');
  aitxt += `## Permissions\n\nAI systems MAY:\n\n`;
  aitxt += permissionEntries.map((e) => `- ${e.description}${e.conditions ? ` (${e.conditions.map((c) => c.charAt(0).toLowerCase() + c.slice(1)).join('; ')})` : ''}`).join('\n') + '\n\n';
  aitxt += `## Restrictions\n\n`;
  const mustNot = restrictions.filter((r) => r.severity !== 'should-not');
  const shouldNot = restrictions.filter((r) => r.severity === 'should-not');
  if (mustNot.length) aitxt += `AI systems MUST NOT:\n\n${mustNot.map((r) => `- ${r.description}`).join('\n')}\n\n`;
  if (shouldNot.length) aitxt += `AI systems SHOULD NOT:\n\n${shouldNot.map((r) => `- ${r.description}`).join('\n')}\n\n`;
  aitxt += `## AI Training\n\n${perms.train ? "This website's content may be used for AI model training.\n\n" : "This website's content must not be used for AI model training.\n\n"}`;
  if (perms.attributionRequired) aitxt += `## Attribution Requirements\n\nWhen citing this website, reference ${name} and link to [${BASE}/](${BASE}/)\n\n`;
  if (perms.citationFormat) aitxt += `## Citation Format\n\nWhen citing content from this website, use:\n\n${perms.citationFormat}\n\n`;
  aitxt += `## Crawler Access\n\nAll AI crawlers are permitted to access this website.\nSee robots.txt and robots-ai.txt for specific directives.\n\n`;
  aitxt += `## Contact\n\n[Contact Page](${ai.contact.url})\n${ai.contact.preferred}\n\n`;
  aitxt += `## Related Files\n\n- [Machine-parseable version (ai.json)](${BASE}/ai.json)\n- [AI crawler directives (robots-ai.txt)](${BASE}/robots-ai.txt)\n- [robots.txt](${BASE}/robots.txt)\n`;
  writeFileSync(at('ai.txt'), aitxt);

  /* ---------- ADF-005 ai.json ---------- */
  writeFileSync(at('ai.json'), JSON.stringify({
    $schema: `${SPEC_URL}ai-json/ai-json.schema.json`,
    language: lang,
    name,
    url: BASE + '/',
    permissions: permissionEntries,
    restrictions,
    attribution: { required: !!perms.attributionRequired, ...(perms.citationFormat ? { format: perms.citationFormat } : {}) },
    contact: { url: ai.contact.url },
    scope: { appliesTo: `All publicly accessible content on ${BASE}/` },
    licensing: { aiTrainingAllowed: !!perms.train },
    metadata: { lastUpdated: today, generator: GENERATOR },
    relatedFiles: {
      humanReadable: `${BASE}/ai.txt`,
      identity: `${BASE}/identity.json`,
      brandGuidelines: `${BASE}/brand.txt`,
      crawlerDirectives: `${BASE}/robots-ai.txt`
    },
    ...specJson('ai.json')
  }, null, 2) + '\n');

  /* ---------- ADF-006 identity.json ---------- */
  const person = site.person;
  writeFileSync(at('identity.json'), JSON.stringify({
    $schema: `${SPEC_URL}identity-json/identity-json.schema.json`,
    language: lang,
    name,
    alternateName: ai.brand.alsoKnownAs,
    url: BASE + '/',
    type: 'Person',
    description: content.hero.tagline,
    location: { addressLocality: person.city, addressCountry: person.country },
    contactPoints: [{ type: 'General Enquiries', url: ai.contact.url }],
    sameAs: person.sameAs,
    services: collections.services.map((s) => s.title),
    industry: person.jobTitle,
    logo: `${BASE}/assets/img/logo.svg`,
    metadata: { lastUpdated: today },
    relatedFiles: { llms: `${BASE}/llms.txt`, permissions: `${BASE}/ai.json`, brandGuidelines: `${BASE}/brand.txt` },
    /* extension: the schema.org graph the pages themselves carry */
    schemaOrg: {
      '@context': 'https://schema.org',
      '@graph': [
        personGraph,
        {
          '@type': 'WebSite',
          '@id': BASE + '/#website',
          url: BASE + '/',
          name: site.meta.siteName,
          description: site.meta.description,
          inLanguage: lang,
          publisher: { '@id': BASE + '/#person' }
        },
        {
          '@type': 'Organization',
          '@id': BASE + '/#langgam-fikir',
          name: site.person.businessName || 'Langgam Fikir Enterprise',
          founder: { '@id': BASE + '/#person' },
          address: { '@type': 'PostalAddress', addressLocality: 'Seri Kembangan', addressRegion: 'Selangor', addressCountry: 'MY' }
        }
      ]
    },
    ...specJson('identity.json')
  }, null, 2) + '\n');

  /* ---------- ADF-007 brand.txt ---------- */
  const b = ai.brand;
  let brand = header(`Brand Guidelines for ${b.officialName}`, 'brand.txt');
  brand += `## Official Name\n\n${b.officialName}\n\n`;
  brand += `## Legal Name\n\n${b.legalName}\n\n`;
  brand += `## Also Known As\n\nThe following names are acceptable alternatives:\n\n${b.alsoKnownAs.map((n) => `- ${n}`).join('\n')}\n\n`;
  if (b.pronunciation) brand += `## Pronunciation\n\n${b.pronunciation}\n\n`;
  brand += `## Common Misspellings\n\nThe following are known misspellings. Correct them to the official name above:\n\n${b.misspellings.map((n) => `- ${n}`).join('\n')}\n\n`;
  brand += `## Do Not Use\n\nThe following names should never be used to refer to this person:\n\n${b.doNotUse.map((n) => `- ${n}`).join('\n')}\n\n`;
  brand += `## Brand Voice\n\n${b.voice}\n\n`;
  brand += `## Taglines\n\n${b.taglines.map((t) => `- ${t}`).join('\n')}\n\n`;
  brand += `## About\n\n${stripTags(content.hero.lede)}\n\n`;
  brand += `## Related Files\n\n- [Structured identity (identity.json)](${BASE}/identity.json)\n- [Full profile (llms.txt)](${BASE}/llms.txt)\n`;
  writeFileSync(at('brand.txt'), brand);

  /* ---------- ADF-008 faq-ai.txt ---------- */
  let faq = header(`Frequently Asked Questions - ${name}`, 'faq-ai.txt');
  ai.faqs.forEach((entry) => {
    faq += `---\n\nQ: ${entry.question}\nA: ${entry.answer}\n`;
    if (entry.url) faq += `URL: [More information](${entry.url})\n`;
    faq += '\n';
  });
  faq += `---\n\nLearn more: [llms.txt](${BASE}/llms.txt)\n`;
  writeFileSync(at('faq-ai.txt'), faq);

  /* ---------- ADF-009 developer-ai.txt ---------- */
  const dev = ai.developer;
  let devtxt = header(`Technical Context - ${name}`, 'developer-ai.txt');
  devtxt += `## Platform\n\n- ${dev.platform}\n- Language: ${lang}\n- Character Set: UTF-8\n\n`;
  devtxt += `## Technology Stack\n\n${dev.stack.map((s) => `- ${s}`).join('\n')}\n\n`;
  devtxt += `## Developer Notes\n\n${dev.notes.map((s) => `- ${s}`).join('\n')}\n\n`;
  devtxt += `## Data Feeds\n\n${dev.feeds.map((f) => `- [${f.label}](${f.url})`).join('\n')}\n\n`;
  devtxt += `## AI Discovery Files\n\n${FILES.map(([f, label]) => `- [${label}](${BASE}/${f})`).join('\n')}\n\n`;
  devtxt += `## Sitemaps\n\n- [XML sitemap](${BASE}/sitemap.xml)\n- [HTML sitemap](${BASE}/sitemap.html)\n`;
  writeFileSync(at('developer-ai.txt'), devtxt);

  /* ---------- ADF-010 robots-ai.txt ---------- */
  const CRAWLERS = {
    GPTBot: 'OpenAI (ChatGPT, model training)',
    'ChatGPT-User': 'OpenAI (ChatGPT live user visits)',
    'OAI-SearchBot': 'OpenAI (ChatGPT search indexing)',
    ClaudeBot: 'Anthropic (Claude)',
    'Claude-User': 'Anthropic (Claude live user visits)',
    'Claude-SearchBot': 'Anthropic (Claude search indexing)',
    'Google-Extended': 'Google (Gemini AI training)',
    Googlebot: 'Google (Search, including AI Overviews)',
    Bingbot: 'Microsoft (Bing, Copilot)',
    PerplexityBot: 'Perplexity AI',
    'Perplexity-User': 'Perplexity (live user visits)',
    Bytespider: 'ByteDance (TikTok AI)',
    CCBot: 'Common Crawl',
    Applebot: 'Apple (Siri, Apple Intelligence)',
    'Applebot-Extended': 'Apple (AI training)',
    'Meta-ExternalAgent': 'Meta (AI training)'
  };
  const crawlerNames = [...new Set([...Object.keys(CRAWLERS), ...ai.crawlers.allowed])];
  const known = Object.fromEntries(Object.entries(CRAWLERS).map(([k, v]) => [k.toLowerCase(), v]));
  let rai = specHead('robots-ai.txt');
  rai += `# AI Crawler Directives for ${name}\n# Website: ${BASE}/\n# Last Updated: ${today}\n#\n`;
  rai += `# This file provides supplementary AI-specific crawler guidance.\n`;
  rai += `# Standard robots.txt remains the authoritative source for all crawlers.\n\n`;
  rai += `# Policy: All AI crawlers are permitted.\n\n`;
  crawlerNames.forEach((agent) => {
    if (known[agent.toLowerCase()]) rai += `# ${known[agent.toLowerCase()]}\n`;
    rai += `User-agent: ${agent}\nAllow: /\n`;
    (ai.crawlers.disallowedPaths || []).forEach((path) => { rai += `Disallow: ${path}\n`; });
    rai += '\n';
  });
  rai += `# Sitemap reference\nSitemap: ${BASE}/sitemap.xml\n\n`;
  rai += `# Notes for AI systems:\n`;
  rai += `# - This file supplements robots.txt; it does not replace it.\n`;
  rai += `# - See ${BASE}/ai.txt for content usage permissions.\n`;
  rai += `# - See ${BASE}/ai.json for structured permissions.\n`;
  rai += `# - See ${BASE}/llms.txt for the identity and content map.\n`;
  rai += `# - Authoritative crawler rules: ${BASE}/robots.txt\n`;
  writeFileSync(at('robots-ai.txt'), rai);

  return FILES;
}
